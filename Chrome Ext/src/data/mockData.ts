const daysAgo = (days: number, hoursOffset = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(d.getHours() - hoursOffset);
  return d.toISOString();
};

const makeStatusChanges = (count: number, created: string): StatusChange[] => {
  const statuses: IssueStatus[] = [
    "Open",
    "In Progress",
    "In Review",
    "Resolved",
    "Reopened",
    "In Progress",
  ];
  const changes: StatusChange[] = [];
  const start = new Date(created);
  for (let i = 0; i < Math.min(count, statuses.length - 1); i++) {
    start.setDate(start.getDate() + 1);
    changes.push({
      from: statuses[i],
      to: statuses[i + 1],
      date: start.toISOString(),
      by: ASSIGNEES[i % ASSIGNEES.length],
    });
  }
  return changes;
};

const makeIssue = (
  n: number,
  priority: Priority,
  status: IssueStatus,
  environment: Environment,
  moduleIdx: number,
  storyIdx: number,
  createdDaysAgo: number,
  timeEstimate: number,
  timeLogged: number,
  commentsCount: number,
  reopenCount: number,
  assigneeIdx: number,
  statusChangeCount: number,
  assigneeChanges: number,
  slaHours: number,
): QAIssue => {
  const created = daysAgo(createdDaysAgo);
  return {
    id: `issue-${n}`,
    key: `PROJ-${200 + n}`,
    summary: getSummary(priority, MODULES[moduleIdx], n),
    description: getDescription(priority, MODULES[moduleIdx]),
    priority,
    status,
    originalStatus: status,
    assignee: ASSIGNEES[assigneeIdx % ASSIGNEES.length],
    reporter: REPORTERS[n % REPORTERS.length],
    created,
    updated: daysAgo(Math.max(createdDaysAgo - 2, 0)),
    resolved:
      status === "Resolved" || status === "Closed"
        ? daysAgo(Math.max(createdDaysAgo - 3, 0))
        : undefined,
    module: MODULES[moduleIdx],
    environment,
    storyKey: STORIES[storyIdx].key,
    storyTitle: STORIES[storyIdx].title,
    labels: getLabels(environment, priority),
    timeEstimate,
    timeLogged,
    commentsCount,
    statusChanges: makeStatusChanges(statusChangeCount, created),
    reopenCount,
    assigneeChanges,
    slaHours,
    issueType: "Bug",
    workratio:
      timeEstimate > 0 ? Math.round((timeLogged / timeEstimate) * 100) : 0,
    worklogs: [],
  };
};

const getSummary = (priority: Priority, module: string, n: number): string => {
  const summaries: Record<Priority, string[]> = {
    Blocker: [
      `${module} - Complete system failure on production`,
      `${module} - Data corruption issue blocking all users`,
      `${module} - Critical API endpoint returning 500`,
    ],
    Critical: [
      `${module} - Payment transaction failing intermittently`,
      `${module} - User authentication broken for mobile users`,
      `${module} - Database deadlock causing data loss`,
    ],
    High: [
      `${module} - Performance degradation under load`,
      `${module} - UI rendering broken on IE11`,
      `${module} - Export functionality returns empty file`,
    ],
    Medium: [
      `${module} - Incorrect calculation in summary report`,
      `${module} - Pagination not working correctly`,
      `${module} - Search results not ordered by relevance`,
    ],
    Low: [
      `${module} - Minor UI misalignment on mobile`,
      `${module} - Tooltip text has typo`,
      `${module} - Unused console.log statements`,
    ],
  };
  const list = summaries[priority];
  return list[n % list.length];
};

const getDescription = (priority: Priority, module: string): string =>
  `[${priority.toUpperCase()}] Issue in ${module} module. ` +
  `This defect was found during regression testing and needs immediate attention. ` +
  `Steps: 1) Navigate to ${module} 2) Perform the affected action 3) Observe the failure. ` +
  `Expected: Normal ${module} behavior. Actual: Failure observed.`;

const getLabels = (env: Environment, priority: Priority): string[] => {
  const labels: string[] = [];
  if (env === "Production") labels.push("Prod", "production");
  if (env === "Staging") labels.push("Stage", "staging");
  if (env === "NPR") labels.push("NPR", "Non-Prod");
  if (env === "Non-Prod") labels.push("NP", "non-prod");
  if (priority === "Blocker" || priority === "Critical")
    labels.push("escalated");
  return labels;
};

